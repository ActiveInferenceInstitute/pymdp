#!/usr/bin/env python3
"""Measure the gate arms and refresh ``docs-mkdocs/development/gate-metrics.md``.

Run through the gate so the recorded numbers always come from the same entry
point contributors and CI use:

    ./gate.sh bench            - measure every arm, rewrite the metrics page
    ./gate.sh bench --check    - verify the page still describes this tree

The page is generated: do not hand-edit the numbers in it. Each arm is measured
twice, once as the raw command the repository documented before the gate existed
and once through ``./gate.sh``, so the dispatcher's own cost stays visible.
"""

from __future__ import annotations

import argparse
import os
import platform
import re
import subprocess
import sys
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs-mkdocs" / "development" / "gate-metrics.md"
GATE = "./gate.sh"


@dataclass(frozen=True)
class Arm:
    name: str
    baseline: list[str]
    timeout: int = 3600


ARMS: tuple[Arm, ...] = (
    Arm("lint", ["uv", "run", "--group", "dev", "ruff", "check"]),
    Arm("test", ["uv", "run", "--group", "test", "pytest", "test", "-n", "2", "-m", "not nightly"]),
    Arm("test-full", ["uv", "run", "--group", "test", "pytest", "test", "-n", "2"]),
    Arm("gnn", ["uv", "run", "--group", "test", "--extra", "gnn", "pytest", "test/test_gnn_bridge.py", "-v"]),
    Arm("notebooks", ["uv", "run", "--group", "test", "--extra", "nb", "python", "scripts/run_notebook_manifest.py", "test/notebooks/ci_notebooks.txt"]),
    Arm("docs", ["./scripts/docs_build.sh"]),
)

COUNT = re.compile(r"(?P<count>\d+) (?P<kind>passed|failed|error|errors|skipped|deselected)")


@dataclass
class Result:
    seconds: float
    exit_code: int
    counts: dict[str, int] = field(default_factory=dict)
    tail: str = ""


def parse_counts(output: str) -> dict[str, int]:
    """Read pytest's final summary line, ignoring progress lines."""
    for line in reversed(output.splitlines()):
        if "passed" not in line and "failed" not in line and "error" not in line:
            continue
        line = line.strip("= ")
        found = {m.group("kind"): int(m.group("count")) for m in COUNT.finditer(line)}
        if found:
            return found
    return {}


def run_arm(argv: list[str], timeout: int) -> Result:
    start = time.perf_counter()
    env = dict(os.environ, NO_MKDOCS_2_WARNING="1")
    proc = subprocess.run(
        argv,
        cwd=ROOT,
        text=True,
        capture_output=True,
        timeout=timeout,
        env=env,
    )
    seconds = time.perf_counter() - start
    output = proc.stdout + proc.stderr
    return Result(seconds=seconds, exit_code=proc.returncode, counts=parse_counts(output), tail=output[-4000:])


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, text=True, capture_output=True, check=True
    ).stdout.strip()


def uv_version() -> str:
    return subprocess.run(["uv", "--version"], cwd=ROOT, text=True, capture_output=True).stdout.strip()


def python_version() -> str:
    venv = ROOT / ".venv" / "bin" / "python"
    exe = venv if venv.exists() else Path(sys.executable)
    return subprocess.run(
        [str(exe), "-c", "import platform; print(platform.python_version())"],
        cwd=ROOT,
        text=True,
        capture_output=True,
    ).stdout.strip()


def describe(result: Result) -> str:
    if not result.counts:
        return f"exit {result.exit_code}"
    parts = [f"{count} {kind}" for kind, count in result.counts.items()]
    return f"exit {result.exit_code} ({', '.join(parts)})"


def render(results: dict[str, tuple[Result, Result]], host: dict[str, str]) -> str:
    lines: list[str] = []
    lines.append("# Gate measurements")
    lines.append("")
    lines.append("<!-- generated by ./gate.sh bench (scripts/gate_metrics.py); do not edit -->")
    lines.append("")
    lines.append(
        "Wall-clock cost of each gate arm, measured on the host below. `Before` is the "
        "raw command this repository documented before `./gate.sh` existed; `After` is "
        "the same work dispatched through the gate. These are records, not budgets: "
        "one run each, so treat sub-second differences as noise."
    )
    lines.append("")
    lines.append("| Recorded | Value |")
    lines.append("| --- | --- |")
    for key, value in host.items():
        lines.append(f"| {key} | {value} |")
    lines.append("")
    lines.append("## Arm wall time")
    lines.append("")
    lines.append("| Arm | Command | Before (s) | After (s) | Result |")
    lines.append("| --- | --- | --- | --- | --- |")
    for arm in ARMS:
        if arm.name not in results:
            continue
        before, after = results[arm.name]
        command = " ".join(arm.baseline)
        lines.append(
            f"| `{arm.name}` | `{command}` | {before.seconds:.1f} | {after.seconds:.1f} | {describe(after)} |"
        )
    lines.append("")
    lines.append("## Test selection")
    lines.append("")
    lines.append("| Arm | Selected | Deselected | Passed |")
    lines.append("| --- | --- | --- | --- |")
    for arm_name, label in (("test", "`test` (nightly deselected)"), ("test-full", "`test-full`")):
        if arm_name not in results:
            continue
        counts = results[arm_name][1].counts
        selected = counts.get("passed", 0) + counts.get("failed", 0) + counts.get("error", 0)
        lines.append(
            f"| {label} | {selected} | {counts.get('deselected', 0)} | {counts.get('passed', 0)} |"
        )
    lines.append("")
    lines.append("## Unmeasured arms")
    lines.append("")
    lines.append(
        "`package` and `bench` are build/lifecycle arms rather than timed suites: "
        "`package` builds the sdist and wheel, installs the wheel into a throwaway "
        "environment and imports it from outside the source tree; `bench` is this page's "
        "producer. `notebooks-nightly` runs the nightly notebook tier and is scheduled "
        "separately. `all` is the concatenation of `lint`, `test`, `gnn`, `docs` and "
        "`notebooks`."
    )
    lines.append("")
    return "\n".join(lines)


def write_doc(text: str) -> None:
    DOC.parent.mkdir(parents=True, exist_ok=True)
    tmp = DOC.with_suffix(".md.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(DOC)


WATCHED = (
    "gate.sh",
    "scripts/gate_metrics.py",
    "scripts/run_notebook_manifest.py",
    "scripts/docs_build.sh",
    "scripts/sync_docs_notebooks.sh",
    "pyproject.toml",
    "mkdocs.yml",
    "pymdp/",
    "test/",
    "examples/",
    "docs-mkdocs/",
)


def check() -> int:
    """Verify the recorded page still describes this tree.

    The page is measured before it is committed, so its commit is normally the
    parent of HEAD; what matters is that the measurement still covers the arms
    and that nothing that feeds an arm changed after it was recorded.
    """
    if not DOC.exists():
        print(f"{DOC.relative_to(ROOT)} is missing; run ./gate.sh bench", file=sys.stderr)
        return 1
    text = DOC.read_text(encoding="utf-8")
    problems: list[str] = []
    for arm in ARMS:
        if f"`{arm.name}`" not in text:
            problems.append(f"arm {arm.name!r} is not recorded")
    recorded = re.search(r"\| Repository commit \| `([0-9a-f]+)` \|", text)
    if not recorded:
        problems.append("no recorded repository commit")
    else:
        commit = recorded.group(1)
        ancestor = subprocess.run(
            ["git", "merge-base", "--is-ancestor", commit, "HEAD"], cwd=ROOT
        )
        if ancestor.returncode != 0:
            problems.append(f"recorded commit {commit[:12]} is not an ancestor of HEAD")
        else:
            changed = subprocess.run(
                ["git", "diff", "--name-only", f"{commit}..HEAD"], cwd=ROOT, text=True, capture_output=True
            ).stdout.split()
            drift = [
                path
                for path in changed
                if path.startswith(WATCHED) and path != DOC.relative_to(ROOT).as_posix()
            ]
            if drift:
                problems.append(
                    "inputs changed since the measurement: " + ", ".join(drift[:5])
                )
    if problems:
        print("gate metrics page is stale:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        return 1
    print("gate metrics page matches the current tree")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the page instead of rewriting it")
    parser.add_argument("--only", default="", help="comma-separated arm names to measure")
    parser.add_argument("--skip", default="", help="comma-separated arm names to leave out")
    args = parser.parse_args()

    if args.check:
        return check()
    commit = git("rev-parse", "HEAD")

    only = {name for name in args.only.split(",") if name}
    skip = {name for name in args.skip.split(",") if name}
    host = {
        "Recorded (UTC)": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
        "Repository commit": f"`{commit}`",
        "Host": f"{platform.system()} {platform.release()} ({platform.machine()})",
        "Python (project `.venv`)": python_version(),
        "uv": uv_version().removeprefix("uv "),
    }

    results: dict[str, tuple[Result, Result]] = {}
    failed = False
    for arm in ARMS:
        if (only and arm.name not in only) or arm.name in skip:
            continue
        print(f"measuring {arm.name} (before)", flush=True)
        before = run_arm(arm.baseline, arm.timeout)
        print(f"  {before.seconds:.1f}s {describe(before)}", flush=True)
        print(f"measuring {arm.name} (after)", flush=True)
        after = run_arm([GATE, arm.name], arm.timeout)
        print(f"  {after.seconds:.1f}s {describe(after)}", flush=True)
        if after.exit_code != 0:
            failed = True
            print(after.tail, file=sys.stderr)
        results[arm.name] = (before, after)

    if only or skip:
        # A partial measurement must not overwrite the recorded page.
        for arm_name, (before, after) in results.items():
            print(f"{arm_name}: {before.seconds:.1f}s -> {after.seconds:.1f}s ({describe(after)})")
        return 1 if failed else 0

    write_doc(render(results, host))
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
